# 性能基准：迷宫生成与求解
#
# 与 maze.wl 算法及随机序列完全一致，用于对照。

单元格宽 = 40
单元格高 = 40
宽 = 单元格宽 * 2 + 1
高 = 单元格高 * 2 + 1

# 固定种子的线性同余生成器
种子 = 98765


def 下一个随机():
    global 种子
    种子 = (种子 * 1103515245 + 12345) % 2147483648
    return 种子


# 方向表：上、下、左、右，步长 2
方向横 = [0, 0, -2, 2]
方向纵 = [-2, 2, 0, 0]

# ---- 初始化：全部是墙 ----
迷宫 = [[1] * 宽 for _ in range(高)]

# ---- 迭代式深度优先回溯，挖出通道 ----
迷宫[1][1] = 0
栈 = [(1, 1)]

while 栈:
    横, 纵 = 栈[-1]

    候选 = []
    for 序 in range(4):
        新横 = 横 + 方向横[序]
        新纵 = 纵 + 方向纵[序]
        if 0 < 新横 < 宽 - 1 and 0 < 新纵 < 高 - 1:
            if 迷宫[新纵][新横] == 1:
                候选.append(序)

    if not 候选:
        栈.pop()
    else:
        方向 = 候选[下一个随机() % len(候选)]
        新横 = 横 + 方向横[方向]
        新纵 = 纵 + 方向纵[方向]
        迷宫[纵 + 方向纵[方向] // 2][横 + 方向横[方向] // 2] = 0
        迷宫[新纵][新横] = 0
        栈.append((新横, 新纵))

# ---- 广度优先搜索求最短路 ----
距离 = [[-1] * 宽 for _ in range(高)]
队列 = [(1, 1)]
距离[1][1] = 0
头 = 0

步横 = [0, 0, -1, 1]
步纵 = [-1, 1, 0, 0]

while 头 < len(队列):
    横, 纵 = 队列[头]
    头 += 1

    for 序 in range(4):
        新横 = 横 + 步横[序]
        新纵 = 纵 + 步纵[序]
        if 0 <= 新横 < 宽 and 0 <= 新纵 < 高:
            if 迷宫[新纵][新横] == 0 and 距离[新纵][新横] < 0:
                距离[新纵][新横] = 距离[纵][横] + 1
                队列.append((新横, 新纵))

# 输出通路总数与最短路长度作为校验
通路数 = sum(行.count(0) for 行 in 迷宫)

print(通路数)
print(距离[高 - 2][宽 - 2])
