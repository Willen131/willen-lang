# 性能基准：冒泡排序一万个元素
#
# 与 sort.wl 算法完全一致（含相同的伪随机序列），用于对照。

数量 = 2000

# 固定种子的线性同余生成器
种子 = 12345
数据 = []
for _ in range(数量):
    种子 = (种子 * 1103515245 + 12345) % 2147483648
    数据.append(种子 % 100000)

# 冒泡排序
for 轮 in range(数量 - 1):
    for 位 in range(数量 - 1 - 轮):
        if 数据[位] > 数据[位 + 1]:
            数据[位], 数据[位 + 1] = 数据[位 + 1], 数据[位]

# 输出首、中、末三个值作为正确性校验
print(数据[0])
print(数据[数量 // 2])
print(数据[数量 - 1])
